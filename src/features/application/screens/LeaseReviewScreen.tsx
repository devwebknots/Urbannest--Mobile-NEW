/**
 * LeaseReviewScreen: the lease the owner generated, opened from the Lease
 * Review journey step (Application Details) once the offer is accepted.
 * Layout from the "Lease Document" design, app standards:
 *  - light top bar: back + "Lease Document", ⋮ (view the accepted offer)
 *  - LeaseIntroCard: "Review Your Lease" + line
 *  - FileCard: PDF tile, size, download / share / full screen
 *  - the lease paper (shared LeaseDocumentPaper) on the page
 *  - Dispute (light, navy rim) | Confirm (brand), side by side, as on
 *    Offer Acceptance
 * Already confirmed (step done): "Lease Confirmed" and no buttons.
 */

import React from 'react';
import { ScrollView, StatusBar, StyleSheet, View, useWindowDimensions } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { AppDialog } from '@/components/AppDialog';
import { Button } from '@/components/Button';
import { MoreVerticalIcon } from '@/components/icons';
import { colors, spacing } from '@/config/theme';
import { CircleIconButton } from '@/features/renter/components/CircleIconButton';
import { LightTopBar } from '@/features/renter/components/LightTopBar';
import { Reveal } from '@/features/renter/components/Reveal';
import { moderateScale as ms } from '@/utils/responsive';
import { DocumentFullScreen } from '../components/DocumentFullScreen';
import { FileCard, LeaseIntroCard } from '../components/LeaseReviewParts';
import { LeaseDocumentPaper } from '../components/SubmittedApplicationParts';
import { LeaseReviewNavigation, useLeaseReview } from '../hooks/useLeaseReview';
import { journeyStore, useJourneyStore } from '../store/journeyStore';
import type { ApplicationRecord } from '../types';

interface Props {
  navigation?: LeaseReviewNavigation;
  route: { params: { record: ApplicationRecord; confirmed?: boolean } };
}

export const LeaseReviewScreen: React.FC<Props> = ({ navigation, route }) => {
  const insets = useSafeAreaInsets();
  const { width } = useWindowDimensions();
  const { record } = route.params;
  // Re-render once confirmed (hides the buttons behind the success dialog)
  useJourneyStore();
  const confirmed = route.params.confirmed === true || journeyStore.isDone(record.id, 'review');
  const vm = useLeaseReview(record, navigation);
  const bottom = Math.max(insets.bottom, spacing.md) + spacing.sm;

  return (
    <View style={styles.root}>
      <StatusBar barStyle="dark-content" />
      <ScrollView
        showsVerticalScrollIndicator={false}
        contentContainerStyle={{
          paddingTop: insets.top + spacing.sm,
          paddingBottom: bottom + spacing.lg,
        }}
      >
        {/* Soft blue glow behind the top of the page (as on Application Details) */}
        <View pointerEvents="none" style={[styles.glow, { width }]} />

        <LightTopBar
          title="Lease Document"
          titleAlign="left"
          onBack={vm.back}
          right={
            <CircleIconButton
              size={ms(40)}
              accessibilityLabel="More options"
              onPress={vm.more}
              icon={<MoreVerticalIcon size={ms(18)} color={colors.navy} />}
            />
          }
        />

        <View style={styles.padded}>
          <Reveal delay={40}>
            <View style={styles.intro}>
              <LeaseIntroCard
                title={confirmed ? 'Lease Confirmed' : 'Review Your Lease'}
                message={
                  confirmed
                    ? 'You confirmed these lease terms. The owner is preparing the final lease agreement.'
                    : 'Your lease has been generated by the owner. Please review the terms and either confirm or dispute if any changes are needed.'
                }
              />
            </View>
          </Reveal>

          <Reveal delay={100}>
            <View style={styles.file}>
              <FileCard
                name={vm.fileName}
                meta={vm.fileSize}
                onDownload={vm.download}
                onShare={vm.share}
                onExpand={vm.openFullScreen}
              />
            </View>
          </Reveal>

          <Reveal delay={160}>
            <View style={styles.paper}>
              <LeaseDocumentPaper doc={vm.document} />
            </View>
          </Reveal>

          {confirmed ? null : (
            <Reveal delay={220}>
              <View style={styles.actions}>
                <Button
                  title="Dispute"
                  variant="light"
                  onPress={vm.dispute}
                  style={[styles.action, styles.dispute]}
                />
                <Button title="Confirm" variant="brand" onPress={vm.confirm} style={styles.action} />
              </View>
            </Reveal>
          )}
        </View>
      </ScrollView>

      {/* Full screen: the lease alone */}
      <DocumentFullScreen
        visible={vm.fullScreen}
        title={vm.fileName}
        doc={vm.document}
        onClose={vm.closeFullScreen}
      />

      <AppDialog {...vm.dialog} />
    </View>
  );
};

// colors.headerGradientEnd (#518EF9) as rgb, for the glow
const BLUE = '81,142,249';

const styles = StyleSheet.create({
  root: {
    flex: 1,
    backgroundColor: colors.pageTint,
  },
  glow: {
    position: 'absolute',
    top: 0,
    left: 0,
    height: ms(420),
    backgroundImage: `radial-gradient(circle at 85% 5%, rgba(${BLUE},0.2) 0%, rgba(${BLUE},0) 55%), linear-gradient(180deg, rgba(${BLUE},0.1) 0%, rgba(${BLUE},0) 100%)`,
  },
  padded: {
    paddingHorizontal: spacing.screenHorizontal,
  },
  intro: {
    marginTop: spacing.lg,
  },
  file: {
    marginTop: spacing.md,
  },
  // Paper a little inset from the cards above, as in the design
  paper: {
    marginTop: spacing.lg,
    marginHorizontal: spacing.sm,
  },
  actions: {
    flexDirection: 'row',
    gap: spacing.md,
    marginTop: spacing.xxl,
  },
  action: {
    flex: 1,
  },
  // Outlined secondary choice (same as Reject on Offer Acceptance)
  dispute: {
    borderWidth: 1,
    borderColor: colors.navy,
  },
});

export default LeaseReviewScreen;
